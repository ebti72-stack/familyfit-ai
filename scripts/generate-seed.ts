/**
 * Generates supabase/seed.sql from the TypeScript reference data so the app and the database
 * always share the same nutrition values. Run: npx tsx scripts/generate-seed.ts
 */
import { writeFileSync } from 'node:fs';
import { FOODS, FOOD_SOURCE } from '../src/data/foods';
import { RECIPES } from '../src/data/recipes';
import { SUB_RULES } from '../src/lib/substitutions';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => `array[${a.map(q).join(',')}]::text[]`;
const lines: string[] = ['-- GENERATED by scripts/generate-seed.ts — do not edit by hand', 'begin;'];
for (const f of Object.values(FOODS)) {
  const n = f.per100;
  lines.push(
    `insert into public.food_items (id,name_ar,name_en,category,kcal,protein_g,carbs_g,fat_g,fiber_g,sugar_g,sat_fat_g,sodium_mg,allergens,source) values (${[
      q(f.id), q(f.ar), q(f.en), q(f.category), n.kcal, n.protein, n.carbs, n.fat, n.fiber, n.sugar, n.satFat, n.sodium,
      f.allergens.length ? arr(f.allergens) : `'{}'`, q(FOOD_SOURCE),
    ].join(',')}) on conflict (id) do update set kcal=excluded.kcal, protein_g=excluded.protein_g, carbs_g=excluded.carbs_g, fat_g=excluded.fat_g, fiber_g=excluded.fiber_g, sugar_g=excluded.sugar_g, sat_fat_g=excluded.sat_fat_g, sodium_mg=excluded.sodium_mg, allergens=excluded.allergens;`,
  );
}
for (const r of RECIPES) {
  const tags = [r.style, ...(r.vegetarian ? ['vegetarian'] : [])];
  lines.push(
    `insert into public.recipes (id,name_ar,name_en,meal_types,category,prep_minutes,cost_tier,kid_friendly,ingredients,steps_ar,steps_en,tags) values (${[
      q(r.id), q(r.ar), q(r.en), `array[${r.mealTypes.map(q).join(',')}]::meal_type[]`, q(r.style), r.prepMinutes, r.cost, r.kidFriendly,
      q(JSON.stringify(r.ingredients.map((i) => ({ food_item_id: i.food, grams: i.grams, substitutes: i.swaps ?? [] })))) + '::jsonb',
      arr(r.stepsAr), arr(r.stepsEn), arr(tags),
    ].join(',')}) on conflict (id) do update set ingredients=excluded.ingredients, steps_ar=excluded.steps_ar, steps_en=excluded.steps_en;`,
  );
}
for (const r of SUB_RULES) {
  lines.push(
    `insert into public.healthy_substitutions (id,from_foods,to_food,ratio,reason_ar,reason_en,taste_ar,taste_en) values (${[
      q(r.id), arr(r.from), r.to === '=' ? 'null' : q(r.to), r.ratio, q(r.reason.ar), q(r.reason.en), q(r.taste.ar), q(r.taste.en),
    ].join(',')}) on conflict (id) do update set from_foods=excluded.from_foods, to_food=excluded.to_food, ratio=excluded.ratio, reason_ar=excluded.reason_ar, reason_en=excluded.reason_en, taste_ar=excluded.taste_ar, taste_en=excluded.taste_en;`,
  );
}
lines.push('commit;', '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'));
console.log(`seed.sql: ${Object.keys(FOODS).length} foods, ${RECIPES.length} recipes, ${SUB_RULES.length} substitutions`);
